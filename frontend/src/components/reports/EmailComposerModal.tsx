import React, { useState } from 'react';
import { api } from '../../services/api';
import { ReportSummary } from '../../types';

interface EmailComposerModalProps {
  report: ReportSummary | null;
  isOpen: boolean;
  onClose: () => void;
  onSuccess?: () => void;
}

export const EmailComposerModal: React.FC<EmailComposerModalProps> = ({
  report,
  isOpen,
  onClose,
  onSuccess,
}) => {
  if (!isOpen || !report) return null;

  const [recipientEmail, setRecipientEmail] = useState('');
  const [recipientName, setRecipientName] = useState('');
  const [subject, setSubject] = useState(`TrustChain AI – Document Verification Report [${report.id}]`);
  const [message, setMessage] = useState(
    `Dear Recipient,\n\nPlease find attached the official document verification report generated by TrustChain AI for ${report.document_name}.\n\nThe dossier contains forensic Error Level Analysis (ELA), OCR text validation, fraud risk scoring, and blockchain smart contract integrity information.\n\nReport Reference: ${report.id}\nVerification Portal: https://trustchain-ai.org/verify/report/${report.id}\n\nRegards,\nTrustChain AI Verification Systems`
  );
  const [selectedFormats, setSelectedFormats] = useState<string[]>(['pdf']);
  const [isSending, setIsSending] = useState(false);
  const [statusResult, setStatusResult] = useState<{
    success: boolean;
    message: string;
    requiresConfig?: boolean;
  } | null>(null);

  const toggleFormat = (fmt: string) => {
    setSelectedFormats((prev) =>
      prev.includes(fmt) ? (prev.length > 1 ? prev.filter((f) => f !== fmt) : prev) : [...prev, fmt]
    );
  };

  const handleSend = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!recipientEmail || !recipientEmail.includes('@')) {
      setStatusResult({ success: false, message: 'Please enter a valid recipient email address.' });
      return;
    }

    setIsSending(true);
    setStatusResult(null);

    try {
      const response = await api.post<any>(`/reports/${report.id}/email`, {
        recipient_email: recipientEmail,
        recipient_name: recipientName || undefined,
        subject,
        message,
        formats: selectedFormats,
      });

      if (response.success) {
        setStatusResult({
          success: true,
          message: response.message || `Report successfully sent to ${recipientEmail}`,
        });
        if (onSuccess) onSuccess();
      } else {
        setStatusResult({
          success: false,
          message: response.message || 'Email delivery failed.',
          requiresConfig: response.requires_smtp_configuration,
        });
      }
    } catch (err: any) {
      setStatusResult({
        success: false,
        message: err.message || 'Failed to dispatch email. Please check network/SMTP configuration.',
      });
    } finally {
      setIsSending(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-fade-in">
      <div className="bg-white dark:bg-slate-900 rounded-xl shadow-2xl border border-slate-200 dark:border-slate-800 w-full max-w-lg overflow-hidden">
        {/* Header */}
        <div className="px-6 py-4 bg-slate-50 dark:bg-slate-800/60 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <span className="text-xl">✉️</span>
            <div>
              <h3 className="text-base font-bold text-slate-900 dark:text-white">
                One-Click Email Report Delivery
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Dispatch dossier <span className="font-mono text-brand-primary font-semibold">{report.id}</span>
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 text-lg font-bold p-1"
          >
            ✕
          </button>
        </div>

        {/* Content Form */}
        <form onSubmit={handleSend} className="p-6 space-y-4">
          {statusResult && (
            <div
              className={`p-3.5 rounded-lg text-xs leading-relaxed ${
                statusResult.success
                  ? 'bg-emerald-50 dark:bg-emerald-950/40 text-emerald-800 dark:text-emerald-300 border border-emerald-200 dark:border-emerald-800'
                  : 'bg-amber-50 dark:bg-amber-950/40 text-amber-800 dark:text-amber-300 border border-amber-200 dark:border-amber-800'
              }`}
            >
              <p className="font-semibold">{statusResult.message}</p>
              {statusResult.requiresConfig && (
                <div className="mt-2 text-[11px] font-mono bg-white/60 dark:bg-black/30 p-2 rounded">
                  💡 Tip: Set SMTP_HOST, SMTP_PORT, and SMTP_USERNAME in backend/.env to connect your live mail server.
                </div>
              )}
            </div>
          )}

          {/* Recipient */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                Recipient Email <span className="text-rose-500">*</span>
              </label>
              <input
                type="email"
                required
                value={recipientEmail}
                onChange={(e) => setRecipientEmail(e.target.value)}
                placeholder="verifier@institution.edu"
                className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-brand-primary"
              />
            </div>
            <div>
              <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
                Recipient Name (Optional)
              </label>
              <input
                type="text"
                value={recipientName}
                onChange={(e) => setRecipientName(e.target.value)}
                placeholder="Dr. Jane Smith"
                className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-brand-primary"
              />
            </div>
          </div>

          {/* Subject */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
              Email Subject
            </label>
            <input
              type="text"
              required
              value={subject}
              onChange={(e) => setSubject(e.target.value)}
              className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-brand-primary"
            />
          </div>

          {/* Message Body */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
              Custom Body Message
            </label>
            <textarea
              rows={4}
              value={message}
              onChange={(e) => setMessage(e.target.value)}
              className="w-full px-3 py-2 text-xs rounded-lg border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-brand-primary font-sans resize-none"
            />
          </div>

          {/* Format Selection */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1.5">
              Select Attachment Formats
            </label>
            <div className="grid grid-cols-4 gap-2">
              {[
                { id: 'pdf', label: 'PDF Document', icon: '📄', color: 'rose' },
                { id: 'docx', label: 'Word (.docx)', icon: '📝', color: 'blue' },
                { id: 'json', label: 'JSON Schema', icon: '⚡', color: 'amber' },
                { id: 'html', label: 'HTML Report', icon: '🌐', color: 'emerald' },
              ].map((fmt) => {
                const isSelected = selectedFormats.includes(fmt.id);
                return (
                  <button
                    key={fmt.id}
                    type="button"
                    onClick={() => toggleFormat(fmt.id)}
                    className={`p-2.5 rounded-lg border text-center transition-all flex flex-col items-center justify-center space-y-1 ${
                      isSelected
                        ? 'border-brand-primary bg-blue-50/60 dark:bg-blue-950/40 text-brand-primary font-bold shadow-sm'
                        : 'border-slate-200 dark:border-slate-800 text-slate-500 hover:border-slate-300'
                    }`}
                  >
                    <span className="text-base">{fmt.icon}</span>
                    <span className="text-[11px] uppercase tracking-wider">{fmt.id}</span>
                  </button>
                );
              })}
            </div>
            <p className="text-[11px] text-slate-400 mt-1">
              Selected formats will be generated on the fly and attached to the email.
            </p>
          </div>

          {/* Actions */}
          <div className="pt-2 flex items-center justify-end space-x-2">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 text-xs font-semibold text-slate-600 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-slate-800 rounded-lg transition-colors"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSending}
              className="px-5 py-2 text-xs font-bold text-white bg-brand-primary hover:bg-blue-700 rounded-lg shadow-sm transition-all flex items-center space-x-1.5 disabled:opacity-50"
            >
              {isSending ? (
                <>
                  <div className="w-3.5 h-3.5 border-2 border-white/20 border-t-white rounded-full animate-spin" />
                  <span>Dispatching...</span>
                </>
              ) : (
                <>
                  <span>Send Report</span>
                  <span>🚀</span>
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};

