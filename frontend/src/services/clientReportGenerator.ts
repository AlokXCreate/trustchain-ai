  /**
   * Universal downloader for any format
   */
  public static download(input: ReportGenerationInput, format: 'pdf' | 'docx' | 'word' | 'json' | 'html'): void {
    const normFormat = format === 'docx' ? 'word' : format;
    switch (normFormat) {
      case 'json':
        this.downloadJson(input);
        break;
      case 'html':
        this.downloadHtml(input);
        break;
      case 'word':
        this.downloadWord(input);
        break;
      case 'pdf':
        this.downloadPdf(input);
        break;
      default:
        this.downloadJson(input);
        break;
    }
  }

