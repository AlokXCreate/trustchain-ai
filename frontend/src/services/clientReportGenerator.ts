/**
 * TrustChain AI – Client-Side Multi-Format Professional Report Generation Engine
 * Generates beautiful, structured reports in PDF, Microsoft Word (.doc), JSON, and HTML
 * with "TRUSTCHAIN AI" prominently branded at the top of every document.
 * Operates 100% in-browser offline or seamlessly enhances live backend data.
 */

export interface ReportGenerationInput {
  reportId: string;
  documentName: string;
  category?: string;
  fileFormat?: string;
  fileSizeBytes?: number;
  sha256?: string;
  riskScore: number;
  riskCategory?: string;
  status: string;
  classificationConfidence?: number;
  extractedFields?: Record<string, any>;
  tamperFindings?: Array<{
    finding: string;
    severity: string;
    confidence: number;
    description: string;
  }>;
  blockchain?: {
    network?: string;
    contractAddress?: string;
    transactionHash?: string | null;
    isRegistered?: boolean;
    blockNumber?: number;
  };
  decision?: {
    recommendation: string;
    rationale: string[];
  };
  generatedAt?: string;
}

